# External QA input and actual framebuffer screenshots, restricted to the selected disposable client.
# Example: .\scripts\Invoke-P6Desktop.ps1 -GameProcessId 1234 -Action inspect
# Included-contract QA: add -ValidationRun embedded-simple; historic P6 paths remain the default.
# Focus is explicit. Later click/hover/wheel/capture/text/key calls refuse a different foreground window.
[CmdletBinding()]
param(
    [Parameter(Mandatory)][ValidateRange(1, 2147483647)][int]$GameProcessId,
    [Parameter(Mandatory)][ValidateSet('inspect', 'focus', 'click', 'hover', 'wheel', 'key', 'text', 'capture')][string]$Action,
    [double]$X = 0, [double]$Y = 0,
    [ValidateRange(100, 7680)][int]$ReferenceWidth = 1280,
    [ValidateRange(100, 4320)][int]$ReferenceHeight = 720,
    [string]$Value = '',
    [ValidatePattern('^[a-z0-9][a-z0-9_-]{0,79}\.png$')][string]$EvidenceName,
    [switch]$RightClick,
    [ValidateSet('p6-public', 'embedded-simple')][string]$ValidationRun = 'p6-public'
)
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
function Assert-NoAlias([string]$Path) {
    $absolute = [IO.Path]::GetFullPath($Path)
    if (-not (Test-Path -LiteralPath $absolute)) { throw 'Required owned path does not exist.' }
    $entry = Get-Item -LiteralPath $absolute -Force
    while ($null -ne $entry) {
        if (($entry.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) { throw 'Reparse point / symlink / junction is not permitted.' }
        $entry = if ($entry -is [IO.DirectoryInfo]) { $entry.Parent } else { $entry.Directory }
    }
    return (Get-Item -LiteralPath $absolute -Force).FullName.TrimEnd('\')
}
$projectDirectory = Assert-NoAlias (Join-Path $PSScriptRoot '..')
$clientDirectory = Assert-NoAlias (Join-Path $projectDirectory "build/$ValidationRun/client")
if (-not ('P6Desktop' -as [type])) { Add-Type -Path (Join-Path $PSScriptRoot 'P6Desktop.cs') -ReferencedAssemblies System.Drawing }

# CIM is read only; never emit/persist the process command line, argument contents, or account data.
$ownedProcess = Get-CimInstance Win32_Process -Filter "ProcessId = $GameProcessId"
if ($null -eq $ownedProcess -or [string]::IsNullOrEmpty($ownedProcess.ExecutablePath) -or
        [IO.Path]::GetFileName($ownedProcess.ExecutablePath) -notin @('java.exe', 'javaw.exe')) { throw 'Selected process is not an inspectable Java executable.' }
$processSnapshot = Get-Process -Id $GameProcessId
$startedAt = $processSnapshot.StartTime.ToUniversalTime().Ticks
if ($processSnapshot.Path -ne $ownedProcess.ExecutablePath) { throw 'Java process identity changed.' }
$processArguments = [P6Desktop]::ParseCommand($ownedProcess.CommandLine)
$expandedArguments = [Collections.Generic.List[string]]::new()
foreach ($argument in $processArguments | Select-Object -Skip 1) {
    if ($argument.StartsWith('@')) {
        # Only the exact argument file generated by the isolated launcher is accepted, no arbitrary reads.
        $argumentPath = [IO.Path]::GetFullPath($argument.Substring(1))
        if ($argumentPath -ne (Join-Path $clientDirectory 'launch-arguments.txt')) { throw 'Unapproved Java argument file.' }
        $argumentPath = Assert-NoAlias $argumentPath
        if ((Get-Item -LiteralPath $argumentPath).Length -gt 262144) { throw 'Java argument file exceeds the safety limit.' }
        foreach ($line in [IO.File]::ReadAllLines($argumentPath)) {
            # Exact writer grammar in Start-ProductionClient.ps1: one fully quoted argument per line.
            if ($line -notmatch '^"((?:[^"\\]|\\[\\"])*)"$') { throw 'Unsupported argument-file grammar; refusing ambiguous ownership.' }
            $decoded = [regex]::Replace($Matches[1], '\\([\\"])', '$1')
            if ($decoded.StartsWith('@')) { throw 'Nested argument files are not allowed.' }
            $expandedArguments.Add($decoded)
        }
    } else { $expandedArguments.Add($argument) }
}
$foundDirectories = [Collections.Generic.List[string]]::new()
for ($argumentIndex = 0; $argumentIndex -lt $expandedArguments.Count; $argumentIndex++) {
    if ($expandedArguments[$argumentIndex] -eq '--gameDir') {
        if ($argumentIndex + 1 -ge $expandedArguments.Count) { throw 'Missing gameDir value.' }
        $foundDirectories.Add((Assert-NoAlias $expandedArguments[$argumentIndex + 1]))
    } elseif ($expandedArguments[$argumentIndex].StartsWith('--gameDir=')) {
        $foundDirectories.Add((Assert-NoAlias $expandedArguments[$argumentIndex].Substring(10)))
    }
}
if ($foundDirectories.Count -ne 1 -or $foundDirectories[0] -ne $clientDirectory) { throw 'Java process is not the selected canonical disposable client.' }
$capturePath = $null
if ($Action -eq 'capture') {
    if ([string]::IsNullOrEmpty($EvidenceName)) { throw 'capture requires -EvidenceName with a unique .png filename.' }
    $evidenceDirectory = Join-Path $projectDirectory "build/$ValidationRun/evidence"
    if (-not (Test-Path -LiteralPath $evidenceDirectory)) {
        $null = Assert-NoAlias (Split-Path -Parent $evidenceDirectory)
        $null = New-Item -ItemType Directory -Path $evidenceDirectory
    }
    $evidenceDirectory = Assert-NoAlias $evidenceDirectory
    $capturePath = [IO.Path]::GetFullPath((Join-Path $evidenceDirectory $EvidenceName))
    if (-not $capturePath.StartsWith(($evidenceDirectory + '\'), [StringComparison]::OrdinalIgnoreCase) -or
            (Test-Path -LiteralPath $capturePath)) { throw 'Evidence target is outside its owned directory or already exists.' }
}
if ((Get-Process -Id $GameProcessId).StartTime.ToUniversalTime().Ticks -ne $startedAt) { throw 'Selected process exited or PID was reused.' }
$window = [P6Desktop]::Act($GameProcessId, $Action, $X, $Y, $ReferenceWidth, $ReferenceHeight, $Value, $capturePath, $RightClick.IsPresent)
$result = [ordered]@{ action = $Action; processId = $GameProcessId; handle = $window.Handle; title = $window.Title;
    width = $window.Width; height = $window.Height; foreground = $window.Foreground; gameDirVerified = $true }
if ($Action -eq 'capture') {
    $result.evidence = $capturePath
    $result.sha256 = (Get-FileHash -LiteralPath $capturePath -Algorithm SHA256).Hash.ToLowerInvariant()
}
[pscustomobject]$result | ConvertTo-Json -Compress
